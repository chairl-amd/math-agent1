#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""一键生成 Windows 启动脚本（.bat），双击即可打开公式批改 Web 演示。

设计约束（与项目铁律一致）：
1. **不写任何密钥**。生成的 .bat 只在运行时解析环境变量，解析顺序为：
   ① 当前进程已设置的 `DEEPSEEK_API_KEY` / `DASHSCOPE_API_KEY`；
   ② 仓库根目录下用户自建的 `.env.local.bat`（可选）；
   ③ 当前用户的持久化环境变量（`setx` 写入的那一份，用 PowerShell 读取）。
   文件本身只有占位提示，密钥永不落到磁盘。
2. **只在仓库内写文件**。桌面位于 C 盘受限区，默认输出到仓库根目录；
   需要桌面副本时显式加 `--desktop`（由有权限的会话执行），写失败会回退到仓库根目录。
3. 使用仓库自带的解释器 `.python312\\python.exe`，与 `README.md` §6.11 一致。

用法：
    .\\.python312\\python.exe scripts\\create_shortcut.py            # 写到仓库根目录
    .\\.python312\\python.exe scripts\\create_shortcut.py --desktop  # 同时尝试写桌面
    .\\.python312\\python.exe scripts\\create_shortcut.py --check    # 只自检，不写文件
    .\\.python312\\python.exe scripts\\create_shortcut.py --force    # 覆盖已存在的 .bat
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[1]
PYTHON_EXE = BASE_DIR / ".python312" / "python.exe"
WEB_APP = BASE_DIR / "web" / "app.py"
BAT_NAME = "start_math_agent.bat"

# 生成脚本的模板：正文为 ASCII + CRLF，避免中文在 cmd 代码页下变成乱码。
# `{python}` / `{app}` 渲染时替换为绝对路径；`%...%` 由 cmd 在运行时展开。
BAT_TEMPLATE = r"""@echo off
rem ============================================================
rem  math-agent one-click demo launcher (generated)
rem  Generated by scripts/create_shortcut.py -- do not edit by hand.
rem  Secrets are NEVER stored here: keys are resolved at runtime.
rem ============================================================
setlocal EnableExtensions
chcp 65001 >nul 2>&1
set "BASE=%~dp0"
if "%BASE:~-1%"=="\" set "BASE=%BASE:~0,-1%"
cd /d "%BASE%"

set "PY={python}"
set "APP={app}"

rem ---------- 0. optional user-provided secrets file (not committed) ----------
if exist "%BASE%\.env.local.bat" (
    call "%BASE%\.env.local.bat"
)

rem ---------- 1. fall back to the per-user persisted environment ----------
if not defined DEEPSEEK_API_KEY call :pull_user_env DEEPSEEK_API_KEY
if not defined DASHSCOPE_API_KEY call :pull_user_env DASHSCOPE_API_KEY

rem ---------- 2. non-secret defaults (safe to pin) ----------
if not defined QWEN_VERIFIER_MODEL set "QWEN_VERIFIER_MODEL=qwen3-vl-plus"
if not defined PYTHONUTF8 set "PYTHONUTF8=1"
if not defined PYTHONIOENCODING set "PYTHONIOENCODING=utf-8"

rem ---------- 3. sanity checks ----------
if not exist "%PY%" (
    echo [ERROR] Python interpreter not found: %PY%
    echo         Run this launcher from the math-agent folder, or reinstall .python312.
    pause
    exit /b 2
)
if not exist "%APP%" (
    echo [ERROR] web\app.py not found: %APP%
    echo         Make sure the file exists, then retry.
    pause
    exit /b 2
)

if /i "%~1"=="--check" goto :check

if not defined DEEPSEEK_API_KEY (
    echo [WARN] DEEPSEEK_API_KEY is not set: the demo cannot call any model yet.
    echo        One-time setup in a normal cmd window:
    echo          setx DEEPSEEK_API_KEY "your-key-here"
    echo        Or drop a .env.local.bat next to this file containing:
    echo          set DEEPSEEK_API_KEY=your-key-here
    echo        Then close this window and double-click this file again.
    echo.
    pause
    exit /b 2
)
if not defined DASHSCOPE_API_KEY (
    echo [INFO] DASHSCOPE_API_KEY is not set: Qwen-VL verifier is skipped,
    echo        the chain falls back to SymPy + DeepSeek.
    echo.
)

echo [INFO] starting web demo -^> http://localhost:7860
echo [INFO] close this window to stop the server.
"%PY%" "%APP%" %*
set "RC=%ERRORLEVEL%"
if not "%RC%"=="0" (
    echo.
    echo [ERROR] web app exited with code %RC%
    pause
)
endlocal & exit /b %RC%

rem ---------- helpers ----------
:pull_user_env
for /f "usebackq delims=" %%V in (`powershell -NoProfile -Command "[Environment]::GetEnvironmentVariable('%~1','User')"`) do set "%~1=%%V"
exit /b 0

:check
echo [CHECK] base   = %BASE%
echo [CHECK] python = %PY%
if exist "%PY%" (echo [CHECK] python exists = yes) else (echo [CHECK] python exists = NO)
echo [CHECK] app    = %APP%
if exist "%APP%" (echo [CHECK] app exists = yes) else (echo [CHECK] app exists = NO)
if defined DEEPSEEK_API_KEY (echo [CHECK] DEEPSEEK_API_KEY = set) else (echo [CHECK] DEEPSEEK_API_KEY = missing)
if defined DASHSCOPE_API_KEY (echo [CHECK] DASHSCOPE_API_KEY = set) else (echo [CHECK] DASHSCOPE_API_KEY = missing)
if defined QWEN_VERIFIER_MODEL (echo [CHECK] QWEN_VERIFIER_MODEL = %QWEN_VERIFIER_MODEL%) else (echo [CHECK] QWEN_VERIFIER_MODEL = missing)
"%PY%" -c "import sys; print('[CHECK] python version =', sys.version.split()[0])" 2>nul
endlocal & exit /b 0
"""

KEY_HINT_LINES = (
    'setx DEEPSEEK_API_KEY "<你的Key>"',
    'setx DASHSCOPE_API_KEY "<你的Key>"',
)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="生成 math-agent 一键启动脚本（不写入任何密钥）")
    parser.add_argument("--desktop", action="store_true",
                        help="同时尝试在用户桌面写一份副本（可能因权限失败）")
    parser.add_argument("--check", action="store_true",
                        help="只做路径自检，不写文件")
    parser.add_argument("--force", action="store_true",
                        help="覆盖已存在的同名 .bat")
    return parser


def desktop_dir() -> Path | None:
    """返回桌面目录；取不到时返回 None。"""
    profile = os.environ.get("USERPROFILE")
    if profile:
        candidate = Path(profile) / "Desktop"
        if candidate.is_dir():
            return candidate
    return None


def check_environment() -> int:
    ok = True
    print(f"[CHECK] BASE_DIR     = {BASE_DIR}")
    print(f"[CHECK] python       = {PYTHON_EXE}  exists={PYTHON_EXE.is_file()}")
    print(f"[CHECK] web/app.py   = {WEB_APP}  exists={WEB_APP.is_file()}")
    if not PYTHON_EXE.is_file():
        print("[FAIL] 缺少解释器：.python312\\python.exe")
        ok = False
    if not WEB_APP.is_file():
        print("[FAIL] 缺少 web/app.py")
        ok = False
    print("[CHECK] DEEPSEEK_API_KEY 已设置 = "
          f"{bool(os.environ.get('DEEPSEEK_API_KEY', '').strip())}")
    print("[CHECK] DASHSCOPE_API_KEY 已设置 = "
          f"{bool(os.environ.get('DASHSCOPE_API_KEY', '').strip())}")
    return 0 if ok else 2


def render_bat() -> str:
    text = BAT_TEMPLATE.format(python=PYTHON_EXE, app=WEB_APP)
    # 统一 CRLF，避免 cmd 把行尾 LF 当成续行
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


def write_bat(target_dir: Path, force: bool = False) -> Path | None:
    target = target_dir / BAT_NAME
    if target.exists() and not force:
        print(f"[SKIP] 已存在，未覆盖：{target}（如需重写加 --force）")
        return target
    target_dir.mkdir(parents=True, exist_ok=True)
    target.write_text(render_bat(), encoding="utf-8", newline="")
    return target


def verify_bat(bat_path: Path) -> bool:
    """用 --check 自检生成结果，不启动服务。"""
    try:
        completed = subprocess.run(
            ["cmd", "/c", str(bat_path), "--check"],
            capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=60, cwd=str(BASE_DIR),
        )
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"[WARN] 自检无法执行：{exc}")
        return False
    output = (completed.stdout or "") + (completed.stderr or "")
    for line in output.splitlines():
        if line.startswith("[CHECK]"):
            print("   " + line)
    passed = (completed.returncode == 0
              and "python exists = yes" in output
              and "app exists = yes" in output)
    print(f"[CHECK] 自检结果 = {'通过' if passed else '未通过'} (exit={completed.returncode})")
    return passed


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.check:
        return check_environment()

    print("== 1/3 环境自检 ==")
    rc = check_environment()
    if rc != 0:
        return rc

    print("\n== 2/3 生成启动脚本 ==")
    repo_bat = write_bat(BASE_DIR, force=args.force)
    if repo_bat is None:
        return 2
    print(f"[OK] 已生成：{repo_bat}  ({repo_bat.stat().st_size} 字节)")

    desktop_bat = None
    if args.desktop:
        target = desktop_dir()
        if target is None:
            print("[WARN] 找不到桌面目录，跳过桌面副本")
        else:
            try:
                desktop_bat = write_bat(target, force=args.force)
                print(f"[OK] 桌面副本：{desktop_bat}")
            except OSError as exc:
                print(f"[WARN] 写桌面失败（{exc.__class__.__name__}: {exc}）")
                desktop_bat = None
        if desktop_bat is None:
            print("[TIP ] 请手动把下面的文件发送到桌面快捷方式：")
            print(f"       {repo_bat}")
    else:
        print("[TIP ] 未指定 --desktop（桌面在 C 盘受限区，默认不写）；")
        print("       需要桌面入口时，在资源管理器里把上面的 .bat 拖到桌面，")
        print("       或右键 → 发送到 → 桌面快捷方式。")

    print("\n== 3/3 生成结果自检（不启动服务）==")
    verified = verify_bat(repo_bat)

    print("\n== 使用说明 ==")
    print("1) 首次使用请先注入密钥（任选其一，脚本内不保存密钥）：")
    for line in KEY_HINT_LINES:
        print("   " + line)
    print("   或在仓库根目录自建 .env.local.bat，内容形如")
    print("     set DEEPSEEK_API_KEY=<你的Key>")
    print("     set DASHSCOPE_API_KEY=<你的Key>")
    print("2) 双击生成的 .bat，浏览器打开 http://localhost:7860")
    print("3) 关闭黑窗口即停止服务")
    print(f"\n最终结果：{'成功' if verified else '已生成但自检未通过，请查看上方提示'}")
    return 0 if verified else 1


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    raise SystemExit(main())
